#pragma once

#include <SDL.h>
#include <cstdint>
#include <vector>

// 外部ライブラリを使わずに文字を出すための、最小限のビットマップフォント。
// 1 文字が 5x7 のドットで、各行の下位 5 ビットがそのままドットの並びになる。
// 描画はドット 1 個を小さな矩形として塗るだけ。

constexpr int FONT_W = 5;
constexpr int FONT_H = 7;

// ASCII 32(' ') 〜 90('Z')
inline const uint8_t* fontGlyph(char ch)
{
    static const uint8_t GLYPHS[59][7] = {
        {0x00,0x00,0x00,0x00,0x00,0x00,0x00}, // ' '
        {0x04,0x04,0x04,0x04,0x04,0x00,0x04}, // !
        {0x0A,0x0A,0x00,0x00,0x00,0x00,0x00}, // "
        {0x0A,0x1F,0x0A,0x0A,0x0A,0x1F,0x0A}, // #
        {0x04,0x0F,0x14,0x0E,0x05,0x1E,0x04}, // $
        {0x18,0x19,0x02,0x04,0x08,0x13,0x03}, // %
        {0x0C,0x12,0x14,0x08,0x15,0x12,0x0D}, // &
        {0x04,0x04,0x00,0x00,0x00,0x00,0x00}, // '
        {0x02,0x04,0x08,0x08,0x08,0x04,0x02}, // (
        {0x08,0x04,0x02,0x02,0x02,0x04,0x08}, // )
        {0x00,0x0A,0x04,0x1F,0x04,0x0A,0x00}, // *
        {0x00,0x04,0x04,0x1F,0x04,0x04,0x00}, // +
        {0x00,0x00,0x00,0x00,0x00,0x04,0x08}, // ,
        {0x00,0x00,0x00,0x0E,0x00,0x00,0x00}, // -
        {0x00,0x00,0x00,0x00,0x00,0x00,0x04}, // .
        {0x01,0x01,0x02,0x04,0x08,0x10,0x10}, // /
        {0x0E,0x11,0x13,0x15,0x19,0x11,0x0E}, // 0
        {0x04,0x0C,0x04,0x04,0x04,0x04,0x0E}, // 1
        {0x0E,0x11,0x01,0x02,0x04,0x08,0x1F}, // 2
        {0x1F,0x02,0x04,0x02,0x01,0x11,0x0E}, // 3
        {0x02,0x06,0x0A,0x12,0x1F,0x02,0x02}, // 4
        {0x1F,0x10,0x1E,0x01,0x01,0x11,0x0E}, // 5
        {0x06,0x08,0x10,0x1E,0x11,0x11,0x0E}, // 6
        {0x1F,0x01,0x02,0x04,0x08,0x08,0x08}, // 7
        {0x0E,0x11,0x11,0x0E,0x11,0x11,0x0E}, // 8
        {0x0E,0x11,0x11,0x0F,0x01,0x02,0x0C}, // 9
        {0x00,0x04,0x04,0x00,0x04,0x04,0x00}, // :
        {0x00,0x04,0x04,0x00,0x04,0x04,0x08}, // ;
        {0x02,0x04,0x08,0x10,0x08,0x04,0x02}, // <
        {0x00,0x00,0x1F,0x00,0x1F,0x00,0x00}, // =
        {0x08,0x04,0x02,0x01,0x02,0x04,0x08}, // >
        {0x0E,0x11,0x01,0x02,0x04,0x00,0x04}, // ?
        {0x0E,0x11,0x17,0x15,0x17,0x10,0x0E}, // @
        {0x0E,0x11,0x11,0x1F,0x11,0x11,0x11}, // A
        {0x1E,0x11,0x11,0x1E,0x11,0x11,0x1E}, // B
        {0x0E,0x11,0x10,0x10,0x10,0x11,0x0E}, // C
        {0x1E,0x11,0x11,0x11,0x11,0x11,0x1E}, // D
        {0x1F,0x10,0x10,0x1E,0x10,0x10,0x1F}, // E
        {0x1F,0x10,0x10,0x1E,0x10,0x10,0x10}, // F
        {0x0E,0x11,0x10,0x17,0x11,0x11,0x0E}, // G
        {0x11,0x11,0x11,0x1F,0x11,0x11,0x11}, // H
        {0x0E,0x04,0x04,0x04,0x04,0x04,0x0E}, // I
        {0x07,0x02,0x02,0x02,0x02,0x12,0x0C}, // J
        {0x11,0x12,0x14,0x18,0x14,0x12,0x11}, // K
        {0x10,0x10,0x10,0x10,0x10,0x10,0x1F}, // L
        {0x11,0x1B,0x15,0x11,0x11,0x11,0x11}, // M
        {0x11,0x19,0x15,0x13,0x11,0x11,0x11}, // N
        {0x0E,0x11,0x11,0x11,0x11,0x11,0x0E}, // O
        {0x1E,0x11,0x11,0x1E,0x10,0x10,0x10}, // P
        {0x0E,0x11,0x11,0x11,0x15,0x12,0x0D}, // Q
        {0x1E,0x11,0x11,0x1E,0x14,0x12,0x11}, // R
        {0x0F,0x10,0x10,0x0E,0x01,0x01,0x1E}, // S
        {0x1F,0x04,0x04,0x04,0x04,0x04,0x04}, // T
        {0x11,0x11,0x11,0x11,0x11,0x11,0x0E}, // U
        {0x11,0x11,0x11,0x11,0x11,0x0A,0x04}, // V
        {0x11,0x11,0x11,0x11,0x15,0x1B,0x11}, // W
        {0x11,0x11,0x0A,0x04,0x0A,0x11,0x11}, // X
        {0x11,0x11,0x0A,0x04,0x04,0x04,0x04}, // Y
        {0x1F,0x01,0x02,0x04,0x08,0x10,0x1F}, // Z
    };

    if (ch >= 'a' && ch <= 'z') ch = (char)(ch - 'a' + 'A');
    if (ch < 32 || ch > 90)     ch = 32;
    return GLYPHS[ch - 32];
}

// 文字列の描画幅（ドットの大きさを px とした時）
inline float textWidth(float px, const char* text)
{
    int n = 0;
    for (const char* p = text; *p; ++p) ++n;
    return n > 0 ? (float)(n * (FONT_W + 1) - 1) * px : 0.0f;
}

inline float textHeight(float px)
{
    return (float)FONT_H * px;
}

// 現在の描画色で文字列を描く。ドットをまとめて 1 回の呼び出しで塗る。
inline void drawText(SDL_Renderer* ren, float x, float y, float px, const char* text)
{
    static std::vector<SDL_FRect> rects;
    rects.clear();

    float cx = x;
    for (const char* p = text; *p; ++p) {
        if (*p != ' ') {
            const uint8_t* g = fontGlyph(*p);
            for (int row = 0; row < FONT_H; ++row) {
                uint8_t bits = g[row];
                for (int col = 0; col < FONT_W; ++col) {
                    if (bits & (1 << (FONT_W - 1 - col))) {
                        rects.push_back(SDL_FRect{ cx + (float)col * px,
                                                   y  + (float)row * px,
                                                   px, px });
                    }
                }
            }
        }
        cx += (float)(FONT_W + 1) * px;
    }

    if (!rects.empty())
        SDL_RenderFillRectsF(ren, rects.data(), (int)rects.size());
}
